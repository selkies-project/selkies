"""Render crates/selkies/src/settings/table.rs from the setting definitions in settings.py.

While the Python server is the definition of record, the Rust server's table is generated
from it, so the two agree on every name, type, default, bound, and help text. The settings
module is read statically, like scripts/generate-settings-doc.py does. Run from anywhere:

    python3 scripts/generate-rust-settings.py          # rewrite the table
    python3 scripts/generate-rust-settings.py --check  # exit 1 if it is stale
"""
import argparse
import ast
import os
import sys
from typing import Any, Dict, List

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SETTINGS_PY = os.path.join(REPO, "src", "selkies", "settings.py")
OUTPUT = os.path.join(REPO, "crates", "selkies", "src", "settings", "table.rs")

HEADER = """\
/*
 * This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at https://mozilla.org/MPL/2.0/.
 */

//! Every setting the server takes, as one declarative table.
//!
//! Generated by `scripts/generate-rust-settings.py` from `src/selkies/settings.py`; edit the
//! definitions there and rerun the script. Each entry names a setting, its type, the default
//! as the text an operator would type, its bounds and menu, the environment variables it
//! also reads, and whether it is a secret or kept from the client payload. The typed
//! accessors on `Settings` at the end are generated from the same table.

use super::{BoolSetting, Kind, Num, SettingDef, Settings};

"""


def load() -> Dict[str, Any]:
    with open(SETTINGS_PY, encoding="utf-8") as f:
        source = f.read()
    tree = ast.parse(source, SETTINGS_PY)
    definitions = sensitive = excluded = None
    for node in tree.body:
        target = None
        if isinstance(node, ast.AnnAssign):
            target = node.target
        elif isinstance(node, ast.Assign) and len(node.targets) == 1:
            target = node.targets[0]
        if not isinstance(target, ast.Name):
            continue
        if target.id == "SETTING_DEFINITIONS":
            definitions = ast.literal_eval(node.value)
        elif target.id == "SENSITIVE_SETTING_NAMES":
            value = node.value
            if isinstance(value, ast.Call) and value.args:
                value = value.args[0]
            sensitive = set(ast.literal_eval(value))
        elif target.id == "CLIENT_PAYLOAD_EXCLUDED":
            excluded = set(ast.literal_eval(node.value))
    if definitions is None or sensitive is None or excluded is None:
        sys.exit("settings.py: definitions, sensitive names, or payload exclusions not found")
    return {"definitions": definitions, "sensitive": sensitive, "excluded": excluded}


def rust_str(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def default_text(value: Any) -> str:
    """The default as Python's `str()` spells it, which is what the resolver parses."""
    return str(value)


def num(value: Any) -> str:
    return "Some(%r)" % float(value) if value is not None else "None"


def kind(stype: str) -> str:
    return {"bool": "Bool", "enum": "Enum", "list": "List", "int": "Int", "float": "Float", "str": "Str", "range": "Range"}[stype]


def accessor_type(stype: str) -> str:
    return {"bool": "BoolSetting", "enum": "&str", "list": "&[String]", "int": "i64", "float": "f64", "str": "&str", "range": "(Num, Num)"}[stype]


def accessor_body(name: str, stype: str) -> str:
    return {
        "bool": f"self.bool_setting({name!r})",
        "enum": f"self.str_value({name!r})",
        "list": f"self.list_value({name!r})",
        "int": f"self.int_value({name!r})",
        "float": f"self.float_value({name!r})",
        "str": f"self.str_value({name!r})",
        "range": f"self.range_value({name!r})",
    }[stype].replace("'", '"')


def render(data: Dict[str, Any]) -> str:
    out: List[str] = [HEADER, "/// The setting definitions, in the order `selkies --help` lists them.\n", "pub static DEFINITIONS: &[SettingDef] = &[\n"]
    for d in data["definitions"]:
        name, stype = d["name"], d["type"]
        meta = d.get("meta") or {}
        env = d.get("env_var") or []
        if isinstance(env, str):
            env = [env]
        allowed = meta.get("allowed") or []
        vr = meta.get("value_range")
        lo = d.get("min", meta.get("min"))
        hi = d.get("max", meta.get("max"))
        out.append("    SettingDef {\n")
        out.append(f"        name: {rust_str(name)},\n")
        out.append(f"        kind: Kind::{kind(stype)},\n")
        out.append(f"        default: {rust_str(default_text(d['default']))},\n")
        out.append(f"        help: {rust_str(d['help'])},\n")
        out.append("        env_vars: &[%s],\n" % ", ".join(rust_str(e) for e in env))
        out.append("        allowed: &[%s],\n" % ", ".join(rust_str(str(a)) for a in allowed))
        out.append("        value_range: %s,\n" % (f"Some(({float(vr[0])!r}, {float(vr[1])!r}))" if vr else "None"))
        out.append(f"        min: {num(lo)},\n")
        out.append(f"        max: {num(hi)},\n")
        out.append(f"        default_value: {num(meta.get('default_value'))},\n")
        out.append(f"        sensitive: {'true' if name in data['sensitive'] else 'false'},\n")
        out.append(f"        client_excluded: {'true' if name in data['excluded'] else 'false'},\n")
        out.append("    },\n")
    out.append("];\n\n")
    out.append("/// One typed reader per setting, named as the setting is; a bool carries its lock.\n")
    out.append("impl Settings {\n")
    for d in data["definitions"]:
        name, stype = d["name"], d["type"]
        out.append(f"    pub fn {name}(&self) -> {accessor_type(stype)} {{\n        {accessor_body(name, stype)}\n    }}\n\n")
    out[-1] = out[-1].rstrip("\n") + "\n"
    out.append("}\n")
    return "".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when the table is stale")
    args = parser.parse_args()
    text = render(load())
    if args.check:
        current = open(OUTPUT, encoding="utf-8").read() if os.path.exists(OUTPUT) else ""
        if current != text:
            print(f"{os.path.relpath(OUTPUT, REPO)} is stale; run scripts/generate-rust-settings.py", file=sys.stderr)
            return 1
        return 0
    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    with open(OUTPUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUTPUT, REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
