"""Render docs/settings.md from the setting definitions in settings.py.

The settings module is read statically (the definition list is a literal), so
this needs no Selkies dependencies and nothing the environment holds can leak
into the page. Run from anywhere:

    python3 scripts/generate-settings-doc.py          # rewrite docs/settings.md
    python3 scripts/generate-settings-doc.py --check  # exit 1 if it is stale
"""

import argparse
import ast
import os
import sys
from typing import Any, Dict, List, Optional, Set

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SETTINGS_PY = os.path.join(REPO, "src", "selkies", "settings.py")
OUTPUT = os.path.join(REPO, "docs", "settings.md")

