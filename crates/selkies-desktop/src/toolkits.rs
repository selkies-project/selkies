//! The applications' theme, derived from the interface colors so GTK, Qt,
//! Chromium, and Electron windows take the shell's light or dark scheme and
//! its accent.  The scheme is dark when the popup color is, and it picks the
//! half of the installed GTK theme pair that matches (Breeze-Dark or Breeze,
//! else GTK's built-in Adwaita-dark or Adwaita), the matching icon theme, and
//! the cursor theme where those are installed.  What each toolkit reads:
//!
//! * GTK 3 and plain GTK 4 read `settings.ini` under `~/.config/gtk-3.0` and
//!   `~/.config/gtk-4.0` for the theme, icon and cursor names and the dark
//!   preference; only those keys of its `[Settings]` group are replaced, so
//!   every other line stays the user's.  On X11 a running `xsettingsd`
//!   overrides that file, so its configuration takes the same names and the
//!   daemon is told to reread it.
//! * GTK on Wayland and libadwaita read GSettings'
//!   `org.gnome.desktop.interface` instead (`color-scheme`, `gtk-theme`,
//!   `icon-theme`, `cursor-theme`), which `gsettings` sets.  Those writes go
//!   through a D-Bus service, so they are made only when the decision
//!   differs from the one last made, recorded in `toolkits.state` under the
//!   shell's config directory, and a start with unchanged settings spawns
//!   nothing.
//! * The accent reaches GTK through its user style sheets: each `gtk.css`
//!   imports a file under the shell's config directory that this module
//!   owns and rewrites, holding GTK's named selection and accent colors and,
//!   for GTK 4, libadwaita's accent variables.  The import is the first line
//!   of `gtk.css`, since CSS takes `@import` only before every rule, and the
//!   user's own rules after it still win over it.
//! * Qt follows GTK through its gtk3 platform theme (`QT_QPA_PLATFORMTHEME`,
//!   set by the image): Qt 6 takes its palette and dark scheme from the GTK
//!   theme, Qt 5 its dialogs and fonts.
//! * Chromium and Electron take `prefers-color-scheme` from the desktop
//!   portal where one answers and otherwise from the GTK theme they load,
//!   which is why the dark scheme is a named dark theme rather than the
//!   preference alone.
//! * libadwaita, Qt 6, Chromium, and Electron read the Settings portal's
//!   `org.freedesktop.appearance` scheme and accent first, which
//!   [`crate::portal`] serves from the same [`Decision`] where no portal of
//!   the image's own holds the name.
//!
//! Every file is written only when its content changes, and a failure is
//! reported on stderr under `SELKIES_DESKTOP_DEBUG` and is never fatal.

use std::path::{Path, PathBuf};

use selkies_draw::dirs;
use selkies_draw::style::{luminance, on_color};
use tiny_skia::Color;

use crate::config::{self, Config};

/// The first line of every style sheet this module writes, which marks it
/// as generated.
const MARKER: &str = "/* Generated by selkies-desktop from its settings; edits are overwritten */";
/// The `settings.ini` group GTK reads its settings from.
const SETTINGS_GROUP: &str = "[Settings]";
/// The GSettings schema GTK on Wayland and libadwaita read.
const INTERFACE_SCHEMA: &str = "org.gnome.desktop.interface";

/// The scheme, theme names, and accent the settings imply, the one value
/// every toolkit setting and the Settings portal are derived from.
#[derive(Clone, Debug, PartialEq)]
pub struct Decision {
    /// Whether the scheme is dark.
    pub dark: bool,
    /// The GTK theme name.
    pub gtk_theme: String,
    /// The icon theme name, or `None` to leave the user's.
    pub icon_theme: Option<String>,
    /// The cursor theme name, or `None` to leave the user's.
    pub cursor_theme: Option<String>,
    /// The accent color.
    pub accent: Color,
}

impl Decision {
    /// The `settings.ini` keys and values of the decision.
    fn settings_ini(&self) -> Vec<(&'static str, String)> {
        let mut values = vec![
            (
                "gtk-application-prefer-dark-theme",
                if self.dark { "1" } else { "0" }.to_string(),
            ),
            ("gtk-theme-name", self.gtk_theme.clone()),
        ];
        if let Some(icons) = &self.icon_theme {
            values.push(("gtk-icon-theme-name", icons.clone()));
        }
        if let Some(cursors) = &self.cursor_theme {
            values.push(("gtk-cursor-theme-name", cursors.clone()));
        }
        values
    }

    /// The XSETTINGS names and values of the decision.
    fn xsettings(&self) -> Vec<(&'static str, String)> {
        let mut values = vec![("Net/ThemeName", self.gtk_theme.clone())];
        if let Some(icons) = &self.icon_theme {
            values.push(("Net/IconThemeName", icons.clone()));
        }
        if let Some(cursors) = &self.cursor_theme {
            values.push(("Gtk/CursorThemeName", cursors.clone()));
        }
        values
    }

    /// The `org.gnome.desktop.interface` keys and values of the decision.
    fn gsettings(&self) -> Vec<(&'static str, String)> {
        let scheme = if self.dark { "prefer-dark" } else { "prefer-light" };
        let mut values = vec![
            ("color-scheme", scheme.to_string()),
            ("gtk-theme", self.gtk_theme.clone()),
        ];
        if let Some(icons) = &self.icon_theme {
            values.push(("icon-theme", icons.clone()));
        }
        if let Some(cursors) = &self.cursor_theme {
            values.push(("cursor-theme", cursors.clone()));
        }
        values
    }
}

/// The directories GTK finds themes in, in its precedence order.
fn theme_roots() -> Vec<PathBuf> {
    let mut roots = vec![dirs::home().join(".themes"), dirs::data_home().join("themes")];
    roots.extend(dirs::data_dirs().into_iter().map(|d| d.join("themes")));
    roots
}

/// The directories icon and cursor themes are found in, in precedence order.
fn icon_roots() -> Vec<PathBuf> {
    let mut roots = vec![dirs::home().join(".icons"), dirs::data_home().join("icons")];
    roots.extend(dirs::data_dirs().into_iter().map(|d| d.join("icons")));
    roots
}

/// Whether a theme of a name has a part under one of the roots.
///
/// # Arguments
/// * `roots` - The directories themes are found in.
/// * `name` - The theme name.
/// * `part` - The path inside the theme that marks it installed.
fn installed(roots: &[PathBuf], name: &str, part: &str) -> bool {
    roots.iter().any(|root| root.join(name).join(part).exists())
}

/// Decides the scheme, the theme names, and the accent for the settings.
/// Adwaita needs no directory since GTK carries it built in; the other names
/// are taken only where installed, so a session never names a theme it
/// cannot load.
pub fn decide(config: &Config) -> Decision {
    let dark = luminance(config.theme.popup) < 0.5;
    let themes = theme_roots();
    let icons = icon_roots();
    let (breeze, adwaita) = if dark {
        ("Breeze-Dark", "Adwaita-dark")
    } else {
        ("Breeze", "Adwaita")
    };
    let gtk_theme = if installed(&themes, breeze, "gtk-3.0") {
        breeze
    } else {
        adwaita
    };
    let icon_theme = config.icon_theme.clone().or_else(|| {
        [dark.then_some("breeze-dark"), Some("breeze")]
            .into_iter()
            .flatten()
            .find(|name| installed(&icons, name, "index.theme"))
            .map(str::to_string)
    });
    let cursor_theme = installed(&icons, "breeze_cursors", "cursors").then(|| "breeze_cursors".to_string());
    Decision {
        dark,
        gtk_theme: gtk_theme.to_string(),
        icon_theme,
        cursor_theme,
        accent: config.theme.accent,
    }
}

/// A color as `#rrggbb`, its alpha dropped.
fn hex(color: Color) -> String {
    let c = color.to_color_u8();
    format!("#{:02x}{:02x}{:02x}", c.red(), c.green(), c.blue())
}

/// GTK's named accent and selection colors for an accent.
fn define_colors(accent: Color) -> String {
    let (bg, fg) = (hex(accent), hex(on_color(accent)));
    format!(
        "@define-color accent_color {bg};\n\
         @define-color accent_bg_color {bg};\n\
         @define-color accent_fg_color {fg};\n\
         @define-color theme_selected_bg_color {bg};\n\
         @define-color theme_selected_fg_color {fg};\n"
    )
}

/// The style sheet GTK 3 imports.
fn gtk3_css(accent: Color) -> String {
    format!("{MARKER}\n{}", define_colors(accent))
}

/// The style sheet GTK 4 imports: the named colors libadwaita before 1.6
/// reads and the variables later releases read.
fn gtk4_css(accent: Color) -> String {
    let (bg, fg) = (hex(accent), hex(on_color(accent)));
    format!(
        "{MARKER}\n{}:root {{\n  --accent-bg-color: {bg};\n  --accent-color: {bg};\n  \
         --accent-fg-color: {fg};\n}}\n",
        define_colors(accent)
    )
}

/// The key of a `key = value` line, or `None` for a comment or a line
/// without one.
fn ini_key(line: &str) -> Option<&str> {
    let line = line.trim_start();
    if line.starts_with('#') || line.starts_with(';') {
        return None;
    }
    line.split_once('=').map(|(key, _)| key.trim())
}

/// A `settings.ini` with keys of its `[Settings]` group set: the first line
/// of each key is replaced, later ones are dropped since a later line would
/// win, keys it lacks are added at the end of the group, and the group is
/// added when there is none.  Every other line is kept as it is.
///
/// # Arguments
/// * `text` - The file's content, empty when there is none.
/// * `values` - The keys and their values.
fn merged_settings_ini(text: &str, values: &[(&str, String)]) -> String {
    let mut out: Vec<String> = Vec::new();
    let mut written = vec![false; values.len()];
    let mut in_group = false;
    let mut group_end: Option<usize> = None;
    let flush = |out: &mut Vec<String>, end: Option<usize>, written: &mut [bool]| {
        let Some(end) = end else { return };
        let missing: Vec<String> = values
            .iter()
            .zip(written.iter_mut())
            .filter(|(_, done)| !**done)
            .map(|((key, value), done)| {
                *done = true;
                format!("{key}={value}")
            })
            .collect();
        out.splice(end..end, missing);
    };
    for line in text.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with('[') {
            if in_group {
                flush(&mut out, group_end.take(), &mut written);
            }
            in_group = trimmed == SETTINGS_GROUP;
            out.push(line.to_string());
            if in_group {
                group_end = Some(out.len());
            }
            continue;
        }
        if in_group && let Some(i) = ini_key(line).and_then(|key| values.iter().position(|(k, _)| *k == key))
        {
            if !written[i] {
                out.push(format!("{}={}", values[i].0, values[i].1));
                written[i] = true;
                group_end = Some(out.len());
            }
            continue;
        }
        out.push(line.to_string());
        if in_group && !trimmed.is_empty() {
            group_end = Some(out.len());
        }
    }
    if in_group {
        flush(&mut out, group_end.take(), &mut written);
    }
    if written.iter().any(|done| !done) {
        if out.last().is_some_and(|line| !line.trim().is_empty()) {
            out.push(String::new());
        }
        out.push(SETTINGS_GROUP.to_string());
        let end = Some(out.len());
        flush(&mut out, end, &mut written);
    }
    let mut merged = out.join("\n");
    merged.push('\n');
    merged
}

/// An `xsettingsd` configuration with settings set: the first line of each
/// name is replaced, later ones are dropped, and names it lacks are
/// appended.  Every other line is kept as it is.
///
/// # Arguments
/// * `text` - The file's content, empty when there is none.
/// * `values` - The setting names and their string values.
fn merged_xsettings(text: &str, values: &[(&str, String)]) -> String {
    let line_for = |(name, value): &(&str, String)| {
        format!("{name} \"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
    };
    let mut out: Vec<String> = Vec::new();
    let mut written = vec![false; values.len()];
    for line in text.lines() {
        let name = line.split_whitespace().next().unwrap_or("");
        if let Some(i) = values.iter().position(|(n, _)| *n == name) {
            if !written[i] {
                out.push(line_for(&values[i]));
                written[i] = true;
            }
            continue;
        }
        out.push(line.to_string());
    }
    for (value, done) in values.iter().zip(&written) {
        if !done {
            out.push(line_for(value));
        }
    }
    let mut merged = out.join("\n");
    merged.push('\n');
    merged
}

/// A user style sheet with an import line as its first line, or `None` when
/// it already has the line.
///
/// # Arguments
/// * `css` - The style sheet, empty when there is none.
/// * `import` - The `@import` line.
fn with_import(css: &str, import: &str) -> Option<String> {
    if css.lines().any(|line| line.trim() == import) {
        return None;
    }
    Some(format!("{import}\n{css}"))
}

/// Writes a file when its content differs, creating its directory.
///
/// # Returns
/// Whether the file changed.
fn write_if_changed(path: &Path, content: &str) -> std::io::Result<bool> {
    if std::fs::read_to_string(path).is_ok_and(|current| current == content) {
        return Ok(false);
    }
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(path, content)?;
    Ok(true)
}

/// The content of a file that may be missing, empty when it is.
fn read_or_empty(path: &Path) -> std::io::Result<String> {
    match std::fs::read_to_string(path) {
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(String::new()),
        other => other,
    }
}

/// Sets keys in a `settings.ini`, creating it when missing.
///
/// # Returns
/// Whether the file changed.
fn write_settings_ini(path: &Path, values: &[(&str, String)]) -> std::io::Result<bool> {
    let text = read_or_empty(path)?;
    write_if_changed(path, &merged_settings_ini(&text, values))
}

/// Makes a user style sheet import another, creating it when missing.
///
/// # Returns
/// Whether the file changed.
fn ensure_import(path: &Path, import: &str) -> std::io::Result<bool> {
    let css = read_or_empty(path)?;
    match with_import(&css, import) {
        Some(edited) => write_if_changed(path, &edited),
        None => Ok(false),
    }
}

/// The processes of a command name running as this user.
fn own_processes(command: &str) -> Vec<i32> {
    let uid = unsafe { libc::getuid() };
    let Ok(entries) = std::fs::read_dir("/proc") else {
        return Vec::new();
    };
    entries
        .flatten()
        .filter_map(|entry| {
            let pid = entry.file_name().to_string_lossy().parse::<i32>().ok()?;
            let comm = std::fs::read_to_string(entry.path().join("comm")).ok()?;
            if comm.trim() != command {
                return None;
            }
            let status = std::fs::read_to_string(entry.path().join("status")).ok()?;
            let owner = status
                .lines()
                .find_map(|line| line.strip_prefix("Uid:"))
                .and_then(|rest| rest.split_whitespace().next())
                .and_then(|v| v.parse::<u32>().ok());
            (owner == Some(uid)).then_some(pid)
        })
        .collect()
}

/// The configuration file a running `xsettingsd` reads: the one its command
/// line names, else its XDG file, else `~/.xsettingsd` where only that one
/// exists.
fn xsettingsd_config(pid: i32) -> PathBuf {
    let proc = PathBuf::from(format!("/proc/{pid}"));
    let cmdline = std::fs::read(proc.join("cmdline")).unwrap_or_default();
    let args: Vec<String> = cmdline
        .split(|b| *b == 0)
        .map(|arg| String::from_utf8_lossy(arg).into_owned())
        .collect();
    let named = args.iter().enumerate().find_map(|(i, arg)| match arg.as_str() {
        "-c" | "--config" => args.get(i + 1).cloned(),
        _ => arg.strip_prefix("--config=").map(str::to_string),
    });
    if let Some(named) = named {
        let path = PathBuf::from(named);
        if path.is_absolute() {
            return path;
        }
        if let Ok(cwd) = std::fs::read_link(proc.join("cwd")) {
            return cwd.join(path);
        }
    }
    let xdg = dirs::config_home().join("xsettingsd/xsettingsd.conf");
    let legacy = dirs::home().join(".xsettingsd");
    if !xdg.exists() && legacy.exists() {
        legacy
    } else {
        xdg
    }
}

/// Sets the theme names in each running `xsettingsd`'s configuration and
/// tells it to reread the file when it changed.
fn apply_xsettings(decision: &Decision) -> std::io::Result<()> {
    let values = decision.xsettings();
    for pid in own_processes("xsettingsd") {
        let path = xsettingsd_config(pid);
        let text = read_or_empty(&path)?;
        if write_if_changed(&path, &merged_xsettings(&text, &values))? {
            unsafe {
                libc::kill(pid, libc::SIGHUP);
            }
        }
    }
    Ok(())
}

/// Sets the GSettings keys through `gsettings` when the decision differs
/// from the one last made; without `gsettings` nothing is recorded, so the
/// keys are set once it appears.
fn apply_gsettings(decision: &Decision) -> std::io::Result<bool> {
    let Some(program) = selkies_draw::apps::resolve_program("gsettings") else {
        return Ok(false);
    };
    let values = decision.gsettings();
    let state: String = values
        .iter()
        .map(|(key, value)| format!("{key}={value}\n"))
        .collect();
    if !write_if_changed(&config::config_dir().join("toolkits.state"), &state)? {
        return Ok(false);
    }
    let program = program.to_string_lossy().into_owned();
    for (key, value) in values {
        let argv = [
            program.clone(),
            "set".into(),
            INTERFACE_SCHEMA.into(),
            key.into(),
            value,
        ];
        selkies_draw::apps::spawn_detached(&argv, None);
    }
    Ok(true)
}

/// Writes the toolkit settings, style sheets, XSETTINGS, and GSettings the
/// settings imply, each only where it changed.
///
/// # Arguments
/// * `config` - The settings.
///
/// # Returns
/// The decision written, for the Settings portal to serve.
pub fn apply(config: &Config) -> Decision {
    let debug = std::env::var_os("SELKIES_DESKTOP_DEBUG").is_some();
    let report = |what: &str, result: std::io::Result<bool>| match result {
        Ok(true) if debug => eprintln!("selkies-desktop: {what} updated"),
        Err(error) if debug => eprintln!("selkies-desktop: cannot update {what}: {error}"),
        _ => {}
    };
    let decision = decide(config);
    let settings = decision.settings_ini();
    let config_home = dirs::config_home();
    let own = config::config_dir();
    let accent = decision.accent;
    let sheets = [
        ("gtk-3.0", "gtk3.css", gtk3_css(accent)),
        ("gtk-4.0", "gtk4.css", gtk4_css(accent)),
    ];
    for (gtk, name, css) in sheets {
        let dir = config_home.join(gtk);
        report(
            &format!("{gtk}/settings.ini"),
            write_settings_ini(&dir.join("settings.ini"), &settings),
        );
        let written = write_if_changed(&own.join(name), &css);
        let imported = written.is_ok();
        report(name, written);
        if imported {
            let import = format!("@import url(\"../selkies-desktop/{name}\");");
            report(
                &format!("{gtk}/gtk.css"),
                ensure_import(&dir.join("gtk.css"), &import),
            );
        }
    }
    report("xsettingsd", apply_xsettings(&decision).map(|()| false));
    report("GSettings", apply_gsettings(&decision));
    decision
}

#[cfg(test)]
mod tests {
    use super::*;

    fn values() -> Vec<(&'static str, String)> {
        vec![
            ("gtk-application-prefer-dark-theme", "1".to_string()),
            ("gtk-theme-name", "Breeze-Dark".to_string()),
        ]
    }

    fn scratch(name: &str) -> PathBuf {
        let dir =
            std::env::temp_dir().join(format!("selkies-desktop-toolkits-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    fn settings_ini_replaces_its_keys_and_keeps_every_other_line() {
        let text = "# mine\n[Settings]\ngtk-theme-name = Yaru\ngtk-font-name=Sans 10\n\
                    gtk-theme-name=Stale\n\n[Other]\ngtk-theme-name=Kept\n";
        assert_eq!(
            merged_settings_ini(text, &values()),
            "# mine\n[Settings]\ngtk-theme-name=Breeze-Dark\ngtk-font-name=Sans 10\n\
             gtk-application-prefer-dark-theme=1\n\n[Other]\ngtk-theme-name=Kept\n"
        );
    }

    #[test]
    fn settings_ini_gains_the_group_when_it_has_none() {
        assert_eq!(
            merged_settings_ini("", &values()),
            "[Settings]\ngtk-application-prefer-dark-theme=1\ngtk-theme-name=Breeze-Dark\n"
        );
        assert_eq!(
            merged_settings_ini("[Other]\nkey=1\n", &values()),
            "[Other]\nkey=1\n\n[Settings]\ngtk-application-prefer-dark-theme=1\ngtk-theme-name=Breeze-Dark\n"
        );
    }

    #[test]
    fn settings_ini_is_created_when_missing_and_settles_after_one_write() {
        let dir = scratch("ini");
        let path = dir.join("gtk-3.0/settings.ini");
        assert!(write_settings_ini(&path, &values()).unwrap());
        assert_eq!(
            std::fs::read_to_string(&path).unwrap(),
            "[Settings]\ngtk-application-prefer-dark-theme=1\ngtk-theme-name=Breeze-Dark\n"
        );
        assert!(!write_settings_ini(&path, &values()).unwrap());
        let _ = std::fs::remove_dir_all(dir);
    }

    #[test]
    fn xsettings_replaces_its_names_and_keeps_every_other_line() {
        let text = "# mine\nNet/ThemeName \"Old\"\nXft/DPI 98304\nNet/ThemeName \"Stale\"\n";
        let values = vec![
            ("Net/ThemeName", "Breeze".to_string()),
            ("Net/IconThemeName", "bree\"ze".to_string()),
        ];
        let merged = merged_xsettings(text, &values);
        assert_eq!(
            merged,
            "# mine\nNet/ThemeName \"Breeze\"\nXft/DPI 98304\nNet/IconThemeName \"bree\\\"ze\"\n"
        );
        assert_eq!(merged_xsettings(&merged, &values), merged);
    }

    #[test]
    fn style_sheet_imports_the_generated_one_exactly_once() {
        let dir = scratch("css");
        let path = dir.join("gtk-3.0/gtk.css");
        let import = "@import url(\"../selkies-desktop/gtk3.css\");";
        assert!(ensure_import(&path, import).unwrap());
        assert_eq!(std::fs::read_to_string(&path).unwrap(), format!("{import}\n"));
        assert!(!ensure_import(&path, import).unwrap());
        std::fs::write(&path, "window { color: red; }\n").unwrap();
        assert!(ensure_import(&path, import).unwrap());
        assert!(!ensure_import(&path, import).unwrap());
        assert_eq!(
            std::fs::read_to_string(&path).unwrap(),
            format!("{import}\nwindow {{ color: red; }}\n")
        );
        let _ = std::fs::remove_dir_all(dir);
    }

    #[test]
    fn style_sheets_carry_the_accent_and_its_readable_text() {
        let accent = crate::render::rgb(0x79, 0x67, 0xc5);
        let gtk3 = gtk3_css(accent);
        assert!(gtk3.starts_with(MARKER));
        assert!(gtk3.contains("@define-color theme_selected_bg_color #7967c5;"));
        assert!(gtk3.contains("@define-color accent_fg_color #ffffff;"));
        let gtk4 = gtk4_css(accent);
        assert!(gtk4.contains("--accent-bg-color: #7967c5;"));
        assert!(gtk4.contains("@define-color accent_bg_color #7967c5;"));
    }
}
