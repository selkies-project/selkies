//! The window manager's theme, generated from the interface colors and the
//! window style so title bars, borders and the right-click menus of labwc
//! and openbox match the bar and the popups.  Both read Openbox 3 theme
//! files and both look under `~/.themes` before the system theme
//! directories, so a theme written there under the name the window
//! manager's `rc.xml` selects shadows the one the image ships, button
//! bitmaps included, and goes away again when it is removed.  The side the
//! buttons sit on and the corner radius are not theme settings but `rc.xml`
//! ones, so those are edited in place: labwc's user file, which the image
//! regenerates at every start, and for openbox a marked copy of the system
//! file under the user's config directory.  A file the user owns or one the
//! image has locked read-only is left alone.  The labwc edit also turns the
//! image's rule that forces server-side decorations on every window into
//! the default, so a client that negotiates its own frame, as browsers,
//! Steam and GTK applications do, is not given a second one over it.
//! After writing, the running window manager is told to reload with the
//! signal each one takes.

use std::path::{Path, PathBuf};

use tiny_skia::Color;

use crate::config::{self, ButtonSide, Config, DEFAULT_CORNERS, Glyphs, Surface, WindowStyle};
use crate::ui::{self, Theme};

/// The first line of every theme file this module writes, which marks it as
/// safe to overwrite or remove.
const MARKER: &str = "# Generated by selkies-desktop from its settings; edits are overwritten";
/// The line that marks an openbox `rc.xml` as this module's copy of the
/// system file.
const RC_MARKER: &str = "<!-- generated by selkies-desktop from the system rc.xml; edits are overwritten -->";
/// The theme name used when `rc.xml` names none.
const DEFAULT_THEME: &str = "Clearlooks";
/// The image's labwc rule that forces server-side decorations on every
/// window, which overrules what clients negotiate.
const FORCED_DECORATION: &str = r#"identifier="*" serverDecoration="yes""#;
/// The same rule letting each client's own preference decide.
const NEGOTIATED_DECORATION: &str = r#"identifier="*" serverDecoration="default""#;
/// Side of the button bitmaps in pixels.
pub const GLYPH: usize = 12;

/// A window manager this module themes.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Manager {
    /// The labwc Wayland compositor.
    Labwc,
    /// The openbox X11 window manager.
    Openbox,
}

/// The colors of the frames and menus, derived from the theme.
#[derive(Clone, Copy, Debug)]
pub struct Palette {
    /// Title bar of the active window, the base of its shading.
    pub title_active: Color,
    /// Title bar of an inactive window.
    pub title_inactive: Color,
    /// Border of the active window.
    pub border_active: Color,
    /// Border of an inactive window.
    pub border_inactive: Color,
    /// Title text of the active window.
    pub label_active: Color,
    /// Title text of an inactive window.
    pub label_inactive: Color,
    /// Button glyphs of the active window, when they are not circles.
    pub button_active: Color,
    /// Button glyphs of an inactive window.
    pub button_inactive: Color,
    /// Background of menus.
    pub menu_bg: Color,
    /// Text of menus.
    pub menu_text: Color,
    /// Background of the highlighted menu item.
    pub menu_active_bg: Color,
    /// Text of the highlighted menu item.
    pub menu_active_text: Color,
    /// Border of menus.
    pub menu_border: Color,
    /// Separators in menus.
    pub menu_separator: Color,
    /// Text of disabled menu items.
    pub menu_disabled: Color,
    /// Background of menu headers.
    pub menu_title_bg: Color,
    /// The accent, for on-screen displays and hovered buttons.
    pub accent: Color,
}

impl Palette {
    /// Derives the palette from the interface colors.
    ///
    /// # Arguments
    /// * `theme` - The interface colors.
    pub fn new(theme: Theme) -> Palette {
        let title_inactive = ui::blend(theme.panel, theme.popup, 0.5);
        Palette {
            title_active: theme.panel,
            title_inactive,
            border_active: ui::blend(theme.panel, theme.text, 0.18),
            border_inactive: ui::blend(title_inactive, theme.text, 0.12),
            label_active: theme.text,
            label_inactive: ui::blend(title_inactive, theme.text, 0.55),
            button_active: theme.text,
            button_inactive: ui::blend(title_inactive, theme.text, 0.4),
            menu_bg: theme.popup,
            menu_text: theme.text,
            menu_active_bg: theme.accent,
            menu_active_text: on_color(theme.accent),
            menu_border: ui::blend(theme.popup, theme.text, 0.14),
            menu_separator: ui::blend(theme.popup, theme.text, 0.11),
            menu_disabled: ui::blend(theme.popup, theme.text, 0.4),
            menu_title_bg: theme.panel,
            accent: theme.accent,
        }
    }

    /// The color of a title bar at a vertical position, shaded in a
    /// surface style the way the theme file describes it.
    ///
    /// # Arguments
    /// * `surface` - The surface style.
    /// * `active` - Whether the window is active.
    /// * `v` - Vertical position from 0 at the top to 1 at the bottom.
    pub fn title_shade(&self, surface: Surface, active: bool, v: f32) -> Color {
        let base = if active {
            self.title_active
        } else {
            self.title_inactive
        };
        ui::surface_shade_in(surface, base, v)
    }

    /// The color of a circle button on the active window.
    ///
    /// # Arguments
    /// * `which` - 0 for close, 1 for iconify, 2 for maximize.
    pub fn circle(which: usize) -> Color {
        crate::render::parse_color(selkies_draw::style::CIRCLES[which.min(2)]).unwrap_or(Color::WHITE)
    }
}

/// Black or white, whichever reads on a color.
fn on_color(color: Color) -> Color {
    if ui::luminance(color) > 0.55 {
        crate::render::rgb(0x10, 0x10, 0x10)
    } else {
        Color::WHITE
    }
}

/// A color as `#rrggbb`, its alpha dropped since openbox reads none.
fn hex(color: Color) -> String {
    let c = color.to_color_u8();
    format!("#{:02x}{:02x}{:02x}", c.red(), c.green(), c.blue())
}

/// A color as `#rrggbbaa`, for the labwc keys that take an alpha.
fn hex_alpha(color: Color, alpha: u8) -> String {
    format!("{}{alpha:02x}", hex(color))
}

/// The texture words and color keys of a title bar in a surface style, for
/// a key prefix such as `window.active.title.bg`.
fn texture_lines(prefix: &str, surface: Surface, base: Color) -> String {
    let shade = |v: f32| hex(ui::surface_shade_in(surface, base, v));
    match surface {
        Surface::Flat => format!("{prefix}: flat solid\n{prefix}.color: {}\n", hex(base)),
        Surface::Gradient => format!(
            "{prefix}: flat gradient vertical\n{prefix}.color: {}\n{prefix}.colorTo: {}\n",
            shade(0.0),
            shade(1.0)
        ),
        Surface::Glossy => format!(
            "{prefix}: flat gradient splitvertical\n{prefix}.color: {}\n{prefix}.color.splitTo: {}\n\
             {prefix}.colorTo: {}\n{prefix}.colorTo.splitTo: {}\n",
            shade(0.49),
            shade(0.0),
            shade(0.5),
            shade(1.0)
        ),
    }
}

/// The theme file for the colors and the style.
///
/// # Arguments
/// * `theme` - The interface colors.
/// * `style` - The window style.
pub fn themerc(theme: Theme, style: WindowStyle) -> String {
    let p = Palette::new(theme);
    let mut out = String::new();
    out.push_str(MARKER);
    out.push('\n');
    let (button_w, button_h, spacing, hover_radius, title_pad) = match style.glyphs {
        Glyphs::Lines => (26, 26, 0, 4, 0),
        Glyphs::Circles => (22, 22, 4, 11, 4),
        Glyphs::Wide => (44, 26, 0, 0, 0),
    };
    let justify = if style.glyphs == Glyphs::Wide {
        "left"
    } else {
        "center"
    };
    out.push_str(&format!(
        "border.width: 1\n\
         padding.width: 6\n\
         padding.height: 4\n\
         window.handle.width: 0\n\
         window.client.padding.width: 0\n\
         window.client.padding.height: 0\n\
         window.titlebar.padding.width: {title_pad}\n\
         window.titlebar.padding.height: 0\n\
         window.button.width: {button_w}\n\
         window.button.height: {button_h}\n\
         window.button.spacing: {spacing}\n\
         window.button.hover.bg.color: {}\n\
         window.button.hover.bg.corner-radius: {hover_radius}\n\
         window.label.text.justify: {justify}\n\n",
        hex_alpha(theme.text, 0x28)
    ));
    for (active, title, border, label, button) in [
        (
            "active",
            p.title_active,
            p.border_active,
            p.label_active,
            p.button_active,
        ),
        (
            "inactive",
            p.title_inactive,
            p.border_inactive,
            p.label_inactive,
            p.button_inactive,
        ),
    ] {
        out.push_str(&format!("window.{active}.border.color: {}\n", hex(border)));
        out.push_str(&texture_lines(
            &format!("window.{active}.title.bg"),
            style.surface,
            title,
        ));
        out.push_str(&format!(
            "window.{active}.title.separator.color: {}\n\
             window.{active}.label.bg: parentrelative\n\
             window.{active}.label.text.color: {}\n\
             window.{active}.handle.bg: flat solid\n\
             window.{active}.handle.bg.color: {}\n\
             window.{active}.grip.bg: flat solid\n\
             window.{active}.grip.bg.color: {}\n\
             window.{active}.button.unpressed.bg: parentrelative\n\
             window.{active}.button.unpressed.image.color: {}\n\
             window.{active}.button.pressed.bg: parentrelative\n\
             window.{active}.button.pressed.image.color: {}\n\
             window.{active}.button.disabled.bg: parentrelative\n\
             window.{active}.button.disabled.image.color: {}\n\
             window.{active}.button.hover.bg: parentrelative\n\
             window.{active}.button.hover.image.color: {}\n\
             window.{active}.button.toggled.unpressed.bg: parentrelative\n\
             window.{active}.button.toggled.unpressed.image.color: {}\n\
             window.{active}.button.toggled.pressed.bg: parentrelative\n\
             window.{active}.button.toggled.pressed.image.color: {}\n\
             window.{active}.button.toggled.hover.bg: parentrelative\n\
             window.{active}.button.toggled.hover.image.color: {}\n",
            hex(title),
            hex(label),
            hex(title),
            hex(title),
            hex(button),
            hex(p.accent),
            hex(ui::blend(title, label, 0.3)),
            hex(if style.glyphs == Glyphs::Circles {
                button
            } else {
                p.accent
            }),
            hex(button),
            hex(p.accent),
            hex(if style.glyphs == Glyphs::Circles {
                button
            } else {
                p.accent
            }),
        ));
        if style.glyphs == Glyphs::Circles {
            let colors = if active == "active" {
                [Palette::circle(0), Palette::circle(1), Palette::circle(2)]
            } else {
                [button; 3]
            };
            for (name, color) in ["close", "iconify", "max"].iter().zip(colors) {
                for state in ["unpressed", "toggled.unpressed", "hover", "toggled.hover"] {
                    out.push_str(&format!(
                        "window.{active}.button.{name}.{state}.image.color: {}\n",
                        hex(color)
                    ));
                }
            }
        }
        out.push('\n');
    }
    out.push_str(&format!(
        "menu.border.width: 1\n\
         menu.border.color: {}\n\
         menu.title.bg: flat solid\n\
         menu.title.bg.color: {}\n\
         menu.title.text.color: {}\n\
         menu.title.text.justify: center\n\
         menu.items.bg: flat solid\n\
         menu.items.bg.color: {}\n\
         menu.items.text.color: {}\n\
         menu.items.disabled.text.color: {}\n\
         menu.items.active.bg: flat solid\n\
         menu.items.active.bg.color: {}\n\
         menu.items.active.text.color: {}\n\
         menu.separator.color: {}\n\
         menu.separator.width: 1\n\
         menu.separator.padding.width: 6\n\
         menu.separator.padding.height: 4\n\n\
         osd.bg.color: {}\n\
         osd.border.width: 2\n\
         osd.border.color: {}\n\
         osd.label.text.color: {}\n\
         osd.window-switcher.style-classic.item.active.bg.color: {}\n\
         osd.window-switcher.style-classic.item.active.border.color: {}\n\
         osd.window-switcher.style-thumbnail.item.active.bg.color: {}\n\
         osd.window-switcher.style-thumbnail.item.active.border.color: {}\n\
         osd.workspace-switcher.boxes.width: 20\n\
         osd.workspace-switcher.boxes.height: 20\n",
        hex(p.menu_border),
        hex(p.menu_title_bg),
        hex(p.menu_text),
        hex(p.menu_bg),
        hex(p.menu_text),
        hex(p.menu_disabled),
        hex(p.menu_active_bg),
        hex(p.menu_active_text),
        hex(p.menu_separator),
        hex(p.menu_bg),
        hex(p.accent),
        hex(p.menu_text),
        hex_alpha(p.accent, 0x50),
        hex(p.accent),
        hex_alpha(p.accent, 0x50),
        hex(p.accent),
    ));
    out
}

/// A button bitmap: the pixels set, row by row.
pub type Bitmap = [[bool; GLYPH]; GLYPH];

/// The bitmap of a button in a glyph style.
///
/// # Arguments
/// * `name` - `close`, `iconify`, `max` or `max_toggled`.
/// * `glyphs` - The glyph style.
pub fn bitmap(name: &str, glyphs: Glyphs) -> Bitmap {
    let mut bits = [[false; GLYPH]; GLYPH];
    let n = GLYPH as i32;
    for (y, row) in bits.iter_mut().enumerate() {
        for (x, bit) in row.iter_mut().enumerate() {
            let (x, y) = (x as i32, y as i32);
            *bit = match (glyphs, name) {
                (Glyphs::Circles, _) => {
                    let c = (n - 1) as f32 / 2.0;
                    let (dx, dy) = (x as f32 - c, y as f32 - c);
                    dx * dx + dy * dy <= (c + 0.5) * (c + 0.5)
                }
                (_, "close") => (x - y).abs() <= 1 || (x + y - (n - 1)).abs() <= 1,
                (Glyphs::Lines, "iconify" | "max" | "max_toggled") => {
                    let c = (n - 1) as f32 / 2.0;
                    let (dx, dy) = ((x as f32 - c).abs(), (y as f32 - c).abs());
                    let reach = c - 1.0;
                    match name {
                        "iconify" => dx <= reach && (y as f32 - (c + reach / 2.0 - dx)).abs() <= 0.75,
                        "max" => dx <= reach && (y as f32 - (c - reach / 2.0 + dx)).abs() <= 0.75,
                        _ => (dx + dy - reach).abs() <= 0.75,
                    }
                }
                (_, "iconify") => y >= n - 3 && y < n - 1 && x >= 1 && x < n - 1,
                (_, "max") => {
                    let edge = x == 1 || x == n - 2 || y == 1 || y == n - 2;
                    edge && (1..n - 1).contains(&x) && (1..n - 1).contains(&y)
                }
                (_, "max_toggled") => {
                    let front = (1..n - 3).contains(&x)
                        && (3..n - 1).contains(&y)
                        && (x == 1 || x == n - 4 || y == 3 || y == n - 2);
                    let back = (y == 1 && (3..n - 1).contains(&x)) || (x == n - 2 && (1..n - 3).contains(&y));
                    front || back
                }
                _ => false,
            };
        }
    }
    bits
}

/// A bitmap in the X bitmap text format the window managers read.
///
/// # Arguments
/// * `name` - The bitmap's name, which names its variables.
/// * `bits` - The pixels set.
fn xbm(name: &str, bits: &Bitmap) -> String {
    let mut bytes = Vec::new();
    for row in bits {
        for chunk in row.chunks(8) {
            let mut byte = 0u8;
            for (i, bit) in chunk.iter().enumerate() {
                if *bit {
                    byte |= 1 << i;
                }
            }
            bytes.push(byte);
        }
    }
    let data: Vec<String> = bytes.iter().map(|b| format!("0x{b:02x}")).collect();
    format!(
        "#define {name}_width {GLYPH}\n#define {name}_height {GLYPH}\nstatic unsigned char {name}_bits[] = {{\n   {} }};\n",
        data.join(", ")
    )
}

/// The bitmap files of a glyph style, by file name.
///
/// # Arguments
/// * `glyphs` - The glyph style.
pub fn bitmaps(glyphs: Glyphs) -> Vec<(String, String)> {
    ["close", "iconify", "max", "max_toggled"]
        .iter()
        .map(|name| (format!("{name}.xbm"), xbm(name, &bitmap(name, glyphs))))
        .collect()
}

/// The user's theme directory.
fn themes_dir() -> PathBuf {
    config::home().join(".themes")
}

/// The window managers running as this user, with their process numbers.
pub fn running() -> Vec<(Manager, i32)> {
    let uid = unsafe { libc::getuid() };
    let mut found = Vec::new();
    let Ok(entries) = std::fs::read_dir("/proc") else {
        return found;
    };
    for entry in entries.flatten() {
        let Ok(pid) = entry.file_name().to_string_lossy().parse::<i32>() else {
            continue;
        };
        let Ok(comm) = std::fs::read_to_string(entry.path().join("comm")) else {
            continue;
        };
        let manager = match comm.trim() {
            "labwc" => Manager::Labwc,
            "openbox" => Manager::Openbox,
            _ => continue,
        };
        let Ok(status) = std::fs::read_to_string(entry.path().join("status")) else {
            continue;
        };
        let owner = status
            .lines()
            .find_map(|line| line.strip_prefix("Uid:"))
            .and_then(|rest| rest.split_whitespace().next())
            .and_then(|v| v.parse::<u32>().ok());
        if owner == Some(uid) {
            found.push((manager, pid));
        }
    }
    found
}

/// The window manager's `rc.xml`: labwc's user file, and for openbox the
/// user file when there is one, else the system file.
fn rc_path(manager: Manager) -> PathBuf {
    let user = config::config_dir()
        .parent()
        .map(Path::to_path_buf)
        .unwrap_or_else(|| config::home().join(".config"));
    match manager {
        Manager::Labwc => user.join("labwc/rc.xml"),
        Manager::Openbox => {
            let own = user.join("openbox/rc.xml");
            if own.is_file() {
                own
            } else {
                PathBuf::from(OPENBOX_SYSTEM_RC)
            }
        }
    }
}

/// The system `rc.xml` of openbox.
const OPENBOX_SYSTEM_RC: &str = "/etc/xdg/openbox/rc.xml";

/// The text between a tag and its closing tag, the first time it occurs
/// after a position.
fn element<'a>(text: &'a str, tag: &str, from: usize) -> Option<(usize, usize, &'a str)> {
    let open = format!("<{tag}>");
    let close = format!("</{tag}>");
    let start = text[from..].find(&open)? + from + open.len();
    let end = text[start..].find(&close)? + start;
    Some((start, end, &text[start..end]))
}

/// The theme name an `rc.xml` selects.
fn theme_name(rc: &str) -> String {
    element(rc, "theme", 0)
        .and_then(|(start, _, _)| element(rc, "name", start))
        .map(|(_, _, name)| name.trim().to_string())
        .filter(|name| !name.is_empty() && !name.contains(['/', '\\']))
        .unwrap_or_else(|| DEFAULT_THEME.to_string())
}

/// The button names in the order they go when the buttons sit on a side:
/// close first on the left, close last on the right.
fn ordered_buttons(side: ButtonSide) -> [&'static str; 5] {
    match side {
        ButtonSide::Left => ["close", "iconify", "max", "shade", "desk"],
        ButtonSide::Right => ["shade", "desk", "iconify", "max", "close"],
    }
}

/// A labwc titlebar layout with its buttons moved to a side, the set of
/// buttons kept as it is so one the image removed stays removed, and the
/// icon and menu moved to the other side.
///
/// # Arguments
/// * `layout` - The layout as in `rc.xml`, `left:right`.
/// * `side` - Where the buttons go.
pub fn labwc_layout(layout: &str, side: ButtonSide) -> String {
    let (left, right) = layout.split_once(':').unwrap_or((layout, ""));
    let items = |part: &str| -> Vec<String> {
        part.split(',')
            .map(|s| s.trim().to_ascii_lowercase())
            .filter(|s| !s.is_empty())
            .collect()
    };
    let (left, right) = (items(left), items(right));
    let is_button = |name: &str| ["close", "iconify", "max", "shade", "desk"].contains(&name);
    let present: Vec<String> = ordered_buttons(side)
        .iter()
        .filter(|name| left.iter().chain(&right).any(|item| item == *name))
        .map(|name| name.to_string())
        .collect();
    let others: Vec<String> = left
        .iter()
        .chain(&right)
        .filter(|item| !is_button(item))
        .cloned()
        .collect();
    match side {
        ButtonSide::Left => format!("{}:{}", present.join(","), others.join(",")),
        ButtonSide::Right => format!("{}:{}", others.join(","), present.join(",")),
    }
}

/// An openbox title layout with its buttons moved to a side, the set of
/// buttons kept as it is and the icon and label on the other side.
///
/// # Arguments
/// * `layout` - The layout letters as in `rc.xml`, such as `NLIMC`.
/// * `side` - Where the buttons go.
pub fn openbox_layout(layout: &str, side: ButtonSide) -> String {
    let letters: Vec<char> = layout.trim().chars().map(|c| c.to_ascii_uppercase()).collect();
    let letter = |name: &str| match name {
        "close" => 'C',
        "iconify" => 'I',
        "max" => 'M',
        "shade" => 'S',
        _ => 'D',
    };
    let present: String = ordered_buttons(side)
        .iter()
        .map(|name| letter(name))
        .filter(|c| letters.contains(c))
        .collect();
    let rest: String = letters.iter().filter(|c| !"CIMSD".contains(**c)).collect();
    match side {
        ButtonSide::Left => format!("{present}{rest}"),
        ButtonSide::Right => format!("{rest}{present}"),
    }
}

/// An `rc.xml` with its titlebar layout and, for labwc, its corner radius
/// set for a style, or set back to the image's defaults when the style is
/// off.  A labwc file's wildcard rule forcing server-side decorations is
/// turned into the default either way, so clients keep the frames they ask
/// for; a wildcard rule that turns decorations off, which the image writes
/// for `NO_DECOR`, is kept.
///
/// # Arguments
/// * `rc` - The file's text.
/// * `manager` - Whose file it is.
/// * `style` - The window style.
fn edited_rc(rc: &str, manager: Manager, style: WindowStyle) -> String {
    let side = if style.decorate {
        style.buttons
    } else {
        ButtonSide::Right
    };
    let mut text = rc.to_string();
    match manager {
        Manager::Labwc => {
            text = text.replace(FORCED_DECORATION, NEGOTIATED_DECORATION);
            if let Some((start, end, layout)) = element(&text, "layout", 0) {
                let new = labwc_layout(layout, side);
                text.replace_range(start..end, &new);
            }
            let corners = if style.decorate {
                style.corners
            } else {
                DEFAULT_CORNERS
            };
            if let Some((start, end, _)) = element(&text, "cornerRadius", 0) {
                text.replace_range(start..end, &corners.to_string());
            } else if let Some((_, end, _)) = element(&text, "theme", 0) {
                text.insert_str(end, &format!("    <cornerRadius>{corners}</cornerRadius>\n  "));
            }
        }
        Manager::Openbox => {
            if let Some((start, end, layout)) = element(&text, "titleLayout", 0) {
                let new = openbox_layout(layout, side);
                text.replace_range(start..end, &new);
            }
        }
    }
    text
}

/// Writes a file when its content differs from what is there.
///
/// # Arguments
/// * `path` - The file.
/// * `content` - The text.
///
/// # Returns
/// Whether the file changed.
fn write_if_changed(path: &Path, content: &str) -> std::io::Result<bool> {
    if std::fs::read_to_string(path).is_ok_and(|current| current == content) {
        return Ok(false);
    }
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(path, content)?;
    Ok(true)
}

/// Writes the theme directory for a name, or removes it when the style is
/// off; returns whether anything changed.
///
/// # Arguments
/// * `name` - The theme name the window manager selects.
/// * `theme` - The interface colors.
/// * `style` - The window style.
fn write_theme(name: &str, theme: Theme, style: WindowStyle) -> std::io::Result<bool> {
    let mut changed = false;
    for sub in ["labwc", "openbox-3"] {
        let dir = themes_dir().join(name).join(sub);
        let themerc_path = dir.join("themerc");
        let ours = std::fs::read_to_string(&themerc_path).is_ok_and(|text| text.starts_with(MARKER));
        if !style.decorate {
            if ours {
                std::fs::remove_dir_all(&dir)?;
                changed = true;
            }
            continue;
        }
        if themerc_path.is_file() && !ours {
            continue;
        }
        changed |= write_if_changed(&themerc_path, &themerc(theme, style))?;
        for (file, text) in bitmaps(style.glyphs) {
            changed |= write_if_changed(&dir.join(file), &text)?;
        }
    }
    if !style.decorate {
        let parent = themes_dir().join(name);
        if parent.is_dir() && std::fs::read_dir(&parent)?.next().is_none() {
            let _ = std::fs::remove_dir(&parent);
        }
    }
    Ok(changed)
}

/// Edits the window manager's `rc.xml` for the style; returns whether it
/// changed.  A labwc file that cannot be written is left alone, and so is
/// an openbox user file that is not this module's copy of the system file.
///
/// # Arguments
/// * `manager` - The window manager.
/// * `style` - The window style.
fn write_rc(manager: Manager, style: WindowStyle) -> std::io::Result<bool> {
    match manager {
        Manager::Labwc => {
            let path = rc_path(manager);
            let Ok(rc) = std::fs::read_to_string(&path) else {
                return Ok(false);
            };
            let edited = edited_rc(&rc, manager, style);
            if edited == rc {
                return Ok(false);
            }
            std::fs::write(&path, edited)?;
            Ok(true)
        }
        Manager::Openbox => {
            let user = config::config_dir()
                .parent()
                .map(Path::to_path_buf)
                .unwrap_or_else(|| config::home().join(".config"))
                .join("openbox/rc.xml");
            let existing = std::fs::read_to_string(&user).ok();
            if existing.as_ref().is_some_and(|text| !text.contains(RC_MARKER)) {
                return Ok(false);
            }
            if !style.decorate {
                if existing.is_some() {
                    std::fs::remove_file(&user)?;
                    return Ok(true);
                }
                return Ok(false);
            }
            let Ok(system) = std::fs::read_to_string(OPENBOX_SYSTEM_RC) else {
                return Ok(false);
            };
            let mut edited = edited_rc(&system, manager, style);
            let at = edited.find('\n').map_or(0, |i| i + 1);
            edited.insert_str(at, &format!("{RC_MARKER}\n"));
            write_if_changed(&user, &edited)
        }
    }
}

/// Tells a running window manager to read its configuration and theme
/// again.
///
/// # Arguments
/// * `manager` - The window manager.
/// * `pid` - Its process number.
fn reload(manager: Manager, pid: i32) {
    let signal = match manager {
        Manager::Labwc => libc::SIGHUP,
        Manager::Openbox => libc::SIGUSR2,
    };
    unsafe {
        libc::kill(pid, signal);
    }
}

/// Writes the theme and the `rc.xml` edits for the settings and reloads
/// the running window manager when either changed.  Without a running
/// window manager nothing is written.
///
/// # Arguments
/// * `config` - The settings.
pub fn apply(config: &Config) {
    let managers = running();
    let Some((manager, _)) = managers.first() else {
        return;
    };
    let name = std::fs::read_to_string(rc_path(*manager))
        .map(|rc| theme_name(&rc))
        .unwrap_or_else(|_| DEFAULT_THEME.to_string());
    let debug = std::env::var_os("SELKIES_DESKTOP_DEBUG").is_some();
    let mut changed = false;
    match write_theme(&name, config.theme, config.window) {
        Ok(did) => changed |= did,
        Err(error) => eprintln!("selkies-desktop: cannot write the window theme: {error}"),
    }
    match write_rc(*manager, config.window) {
        Ok(did) => changed |= did,
        Err(error) if debug => eprintln!("selkies-desktop: rc.xml left as it is: {error}"),
        Err(_) => {}
    }
    if changed {
        if debug {
            eprintln!("selkies-desktop: window theme {name} written, reloading {manager:?}");
        }
        for (manager, pid) in &managers {
            reload(*manager, *pid);
        }
    }
}

