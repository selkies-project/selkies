/// A Rust string literal, quotes included.
const STRING: &str = r#""(?:[^"\\]|\\.)*""#;
static STRING_RE: LazyLock<Regex> = LazyLock::new(|| Regex::new(STRING).expect("a valid pattern"));

/// A bound or default of the table, which stores every one as an `f64`.
#[derive(Clone, Copy, Debug, PartialEq)]
enum Number {
    Int(i64),
    Float(f64),
}

impl std::fmt::Display for Number {
    /// An integer as its digits, and any other number with a fraction (`10.0`, `0.5`).
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Int(value) => write!(f, "{value}"),
            Self::Float(value) => write!(f, "{value:?}"),
        }
    }
}

/// One entry of the table, as the page needs it.
struct Setting {
    name: String,
    /// `bool`, `enum`, `list`, `int`, `float`, `str`, or `range`.
    kind: &'static str,
    default: String,
    help: String,
    env_vars: Vec<String>,
    min: Option<Number>,
    max: Option<Number>,
    allowed: Vec<String>,
    value_range: Option<(Option<Number>, Option<Number>)>,
    /// `Some(None)` for a default the table gives in a form that is not a number.
    default_value: Option<Option<Number>>,
    sensitive: bool,
}

/// The value of a Rust string literal as the table writes them: quotes, backslashes, and
/// newlines escaped.
fn rust_string(literal: &str) -> String {
    let mut value = String::new();
    let mut chars = literal[1..literal.len() - 1].chars();
    while let Some(c) = chars.next() {
        match (c, chars.clone().next()) {
            ('\\', Some(escaped)) if escaped != '\n' => {
                chars.next();
                value.push(match escaped {
                    'n' => '\n',
                    't' => '\t',
                    other => other,
                });
            }
            _ => value.push(c),
        }
    }
    value
}

/// The `name: value` fields of a struct literal's body, split on the commas outside its
/// strings and brackets, each with its whitespace collapsed.
fn top_level_fields(block: &str) -> Vec<String> {
    static SPACE: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"\s+").expect("a valid pattern"));
    let (mut fields, mut depth, mut quoted, mut escaped, mut start) =
        (Vec::new(), 0, false, false, 0);
    for (at, c) in block.char_indices() {
        if quoted {
            if escaped {
                escaped = false;
            } else {
                escaped = c == '\\';
                quoted = c != '"';
            }
        } else if c == '"' {
            quoted = true;
        } else if "([{".contains(c) {
            depth += 1;
        } else if ")]}".contains(c) {
            depth -= 1;
        } else if c == ',' && depth == 0 {
            fields.push(&block[start..at]);
            start = at + 1;
        }
    }
    fields.push(&block[start..]);
    fields
        .into_iter()
        .map(|field| SPACE.replace_all(field, " ").trim().to_string())
        .filter(|field| !field.is_empty())
        .map(|field| {
            field
                .replace("[ ", "[")
                .replace(", ]", "]")
                .replace("(( ", "((")
        })
        .collect()
}

/// `Some(x)` as a number, an integral one as an integer, else `None`.
fn rust_number(text: &str) -> Option<Number> {
    static SOME: LazyLock<Regex> =
        LazyLock::new(|| Regex::new(r"^Some\((-?[0-9.e+-]+)\)$").expect("a valid pattern"));
    let value: f64 = SOME.captures(text.trim())?[1].parse().ok()?;
    Some(if value.fract() == 0.0 && value.abs() < 1e15 {
        Number::Int(value as i64)
    } else {
        Number::Float(value)
    })
}

/// The settings of the table in its order.
fn load_definitions(table: &str) -> Result<Vec<Setting>, String> {
    static BLOCK: LazyLock<Regex> =
        LazyLock::new(|| Regex::new(r"(?s)SettingDef \{(.*?)\n    \}").expect("a valid pattern"));
    static RANGE: LazyLock<Regex> =
        LazyLock::new(|| Regex::new(r"^Some\(\((.*), (.*)\)\)$").expect("a valid pattern"));
    let strings = |text: &str| -> Vec<String> {
        STRING_RE
            .find_iter(text)
            .map(|m| rust_string(m.as_str()))
            .collect()
    };
    let mut definitions = Vec::new();
    for block in BLOCK.captures_iter(table) {
        let fields: HashMap<String, String> = top_level_fields(&block[1])
            .into_iter()
            .filter_map(|field| {
                field
                    .split_once(": ")
                    .map(|(k, v)| (k.to_string(), v.to_string()))
            })
            .collect();
        let field = |name: &str| {
            fields
                .get(name)
                .map(String::as_str)
                .ok_or_else(|| format!("{TABLE_RS}: a SettingDef has no `{name}`"))
        };
        let kind = match field("kind")?.split("::").nth(1) {
            Some("Bool") => "bool",
            Some("Enum") => "enum",
            Some("List") => "list",
            Some("Int") => "int",
            Some("Float") => "float",
            Some("Str") => "str",
            Some("Range") => "range",
            other => return Err(format!("{TABLE_RS}: unknown setting kind {other:?}")),
        };
        let as_float = |number: Option<Number>| match number {
            Some(Number::Int(value)) if kind == "float" => Some(Number::Float(value as f64)),
            other => other,
        };
        definitions.push(Setting {
            name: rust_string(field("name")?),
            kind,
            default: rust_string(field("default")?),
            help: rust_string(field("help")?),
            env_vars: strings(field("env_vars")?),
            min: as_float(rust_number(field("min")?)),
            max: as_float(rust_number(field("max")?)),
            allowed: strings(field("allowed")?),
            value_range: RANGE.captures(field("value_range")?).map(|range| {
                let bound = |at: usize| rust_number(&format!("Some({})", &range[at]));
                (bound(1), bound(2))
            }),
            default_value: match field("default_value")? {
                "None" => None,
                value => Some(rust_number(value)),
            },
            sensitive: field("sensitive")? == "true",
        });
    }
    if definitions.is_empty() {
        return Err(format!("no SettingDef entries found in {TABLE_RS}"));
    }
    Ok(definitions)
}

/// The value-syntax part of the settings module's docblock, as a section of the page.
fn syntax_section(module: &str) -> String {
    let docblock: Vec<&str> = module
        .lines()
        .filter(|line| line.starts_with("//!"))
        .map(|line| line.strip_prefix("//! ").unwrap_or(&line[3..]))
        .collect();
    let docblock = docblock.join("\n");
    let Some(start) = docblock.find("Override value syntax") else {
        return String::new();
    };
    let bullets = docblock[start..]
        .trim()
        .split_once('\n')
        .map_or("", |(_, bullets)| bullets);
    format!("## Value syntax\n\n{}\n", bullets.trim())
}

/// A table cell's text: pipes end cells and newlines end rows.
fn cell(text: &str) -> String {
    text.replace('|', "\\|")
        .replace('\n', " ")
        .trim()
        .to_string()
}

fn code(text: &str) -> String {
    format!("`{}`", cell(text))
}

/// The text of an optional number, `None` where the table's value was not one.
fn number_text(number: Option<Number>) -> String {
    number.map_or_else(|| "None".into(), |number| number.to_string())
}

impl Setting {
    /// The flag and the environment variables that set it, one per line of the cell.
    fn names_cell(&self) -> String {
        let mut names = vec![format!("SELKIES_{}", self.name.to_uppercase())];
        for name in &self.env_vars {
            if !names.contains(name) {
                names.push(name.clone());
            }
        }
        let names: Vec<String> = names.iter().map(|name| code(name)).collect();
        format!(
            "{}<br>{}",
            code(&format!("--{}", self.name.replace('_', "-"))),
            names.join(", ").replace(", ", "<br>")
        )
    }

    /// The type, with a number's bounds or an enumeration's choices.
    fn type_cell(&self) -> String {
        match self.kind {
            "int" | "float" => match (self.min, self.max) {
                (None, None) => self.kind.to_string(),
                (None, Some(high)) => format!("{}, up to {high}", self.kind),
                (Some(low), None) => format!("{}, from {low}", self.kind),
                (Some(low), Some(high)) => format!("{}, {low} to {high}", self.kind),
            },
            "range" => format!("range, within {}", code(&self.default)),
            "enum" | "list" => {
                let choices: Vec<String> = self.allowed.iter().map(|choice| code(choice)).collect();
                let label = if self.kind == "enum" {
                    "one of"
                } else {
                    "any of"
                };
                let mut text = if choices.is_empty() {
                    self.kind.to_string()
                } else {
                    format!("{}: {label} {}", self.kind, choices.join(", "))
                };
                if let Some((low, high)) = self.value_range {
                    text += &format!(
                        ", or any value from {} to {}",
                        number_text(low),
                        number_text(high)
                    );
                }
                text
            }
            kind => kind.to_string(),
        }
    }

    fn default_cell(&self) -> String {
        match self.kind {
            "bool" => code(if self.default == "True" {
                "true"
            } else {
                "false"
            }),
            "range" => code(&self.default_value.map(number_text).unwrap_or_default()),
            _ if self.default.is_empty() => "(empty)".into(),
            _ => code(&self.default),
        }
    }

    fn row(&self) -> String {
        format!(
            "| {} | {}<br>{} | {}{} |\n",
            self.names_cell(),
            self.default_cell(),
            cell(&self.type_cell()),
            cell(&self.help),
            if self.sensitive {
                " Never sent to clients."
            } else {
                ""
            }
        )
    }
}

/// The whole page, or what keeps [`SECTIONS`] from placing every setting exactly once.
fn render(table: &str, module: &str) -> Result<String, String> {
    let definitions = load_definitions(table)?;
    let placed: Vec<&str> = SECTIONS
        .iter()
        .flat_map(|section| section.names)
        .copied()
        .collect();
    let unknown: Vec<&str> = placed
        .iter()
        .copied()
        .filter(|name| definitions.iter().all(|setting| setting.name != *name))
        .collect();
    let missing: Vec<&str> = definitions
        .iter()
        .map(|setting| setting.name.as_str())
        .filter(|name| !placed.contains(name))
        .collect();
    let repeated: Vec<&str> = placed
        .iter()
        .enumerate()
        .filter(|(at, name)| placed[..*at].contains(name))
        .map(|(_, name)| *name)
        .collect();
    if !(unknown.is_empty() && missing.is_empty() && repeated.is_empty()) {
        return Err(format!(
            "SECTIONS names settings that do not exist: {unknown:?}; leaves out: {missing:?}; repeats: {repeated:?}"
        ));
    }
    let mut page = format!("{HEADER}{}\n", syntax_section(module));
    for section in SECTIONS {
        page += &format!("## {}\n\n{}\n\n{TABLE_HEAD}", section.title, section.lead);
        for name in section.names {
            if let Some(setting) = definitions.iter().find(|setting| setting.name == *name) {
                page += &setting.row();
            }
        }
        page.push('\n');
    }
    Ok(format!("{}\n", page.trim_end_matches('\n')))
}

/// Rewrite the page, or under `check` say whether it is current; `Ok(false)` when it is not.
pub fn run(check: bool) -> Result<bool, String> {
    let read =
        |name: &str| fs::read_to_string(repo().join(name)).map_err(|e| format!("{name}: {e}"));
    let rendered = render(&read(TABLE_RS)?, &read(MODULE_RS)?)?;
    if check {
        if fs::read_to_string(repo().join(OUTPUT)).is_ok_and(|current| current == rendered) {
            println!("{OUTPUT} is up to date");
            return Ok(true);
        }
        eprintln!("{OUTPUT} is out of date; run cargo xtask settings-doc");
        return Ok(false);
    }
    fs::write(repo().join(OUTPUT), &rendered).map_err(|e| format!("{OUTPUT}: {e}"))?;
    let rows = rendered
        .lines()
        .filter(|line| line.starts_with("| `--"))
        .count();
    println!("wrote {OUTPUT} ({rows} settings)");
    Ok(true)
}

